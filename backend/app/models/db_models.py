"""
SQLAlchemy ORM models for the campus scheduler database.

These models mirror the schema defined in the Alembic migrations.
They are used for:
- Type-safe queries in the FastAPI application
- Test assertions about schema structure
- IDE autocompletion

NOTE: Migrations are written as raw SQL (not autogenerated from these models)
to maintain full control over PostgreSQL-specific features (RLS, triggers,
SECURITY DEFINER functions, column-level grants).
"""

from __future__ import annotations

import uuid
from datetime import datetime

from sqlalchemy import (
    Boolean,
    CheckConstraint,
    Column,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
)
from sqlalchemy.dialects.postgresql import INET, JSONB, UUID
from sqlalchemy.orm import DeclarativeBase, relationship


class Base(DeclarativeBase):
    """Base class for all ORM models."""
    pass


class Profile(Base):
    __tablename__ = "profiles"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    email = Column(Text, nullable=False)
    full_name = Column(Text, nullable=False, default="")
    role = Column(
        Text, nullable=False, default="faculty",
    )
    department = Column(Text, nullable=True)
    faculty_id = Column(Text, nullable=True)
    created_at = Column(DateTime(timezone=True), nullable=False, default=datetime.now)
    updated_at = Column(DateTime(timezone=True), nullable=False, default=datetime.now)

    __table_args__ = (
        CheckConstraint(
            "role IN ('admin', 'department_coordinator', 'faculty', 'club')",
            name="profiles_role_check",
        ),
        Index("idx_profiles_email", "email"),
        Index("idx_profiles_role", "role"),
    )


class TimetableRun(Base):
    __tablename__ = "timetable_runs"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    dataset_id = Column(Text, nullable=False)
    solver_status = Column(Text, nullable=False)
    total_sessions = Column(Integer, nullable=False)
    scheduled_count = Column(Integer, nullable=False)
    solve_time_sec = Column(Float, nullable=False, default=0)
    diagnostics = Column(JSONB, nullable=False, default=dict)
    is_active = Column(Boolean, nullable=False, default=False)
    created_by = Column(UUID(as_uuid=True), ForeignKey("profiles.id"), nullable=False)
    created_at = Column(DateTime(timezone=True), nullable=False, default=datetime.now)

    entries = relationship("TimetableEntry", back_populates="run", cascade="all, delete-orphan")


class TimetableEntry(Base):
    __tablename__ = "timetable_entries"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    run_id = Column(UUID(as_uuid=True), ForeignKey("timetable_runs.id", ondelete="CASCADE"), nullable=False)
    session_id = Column(Text, nullable=False)
    course_id = Column(Text, nullable=False)
    faculty_id = Column(Text, nullable=False)
    group_id = Column(Text, nullable=False)
    room_id = Column(Text, nullable=False)
    day = Column(Text, nullable=False)
    period = Column(Integer, nullable=False)
    duration = Column(Integer, nullable=False, default=1)

    run = relationship("TimetableRun", back_populates="entries")

    __table_args__ = (
        UniqueConstraint("run_id", "session_id", name="uq_te_run_session"),
    )


class BookingRequest(Base):
    __tablename__ = "booking_requests"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    request_code = Column(Text, nullable=False, unique=True)
    submitted_at = Column(DateTime(timezone=True), nullable=False, default=datetime.now)
    submitted_by = Column(UUID(as_uuid=True), ForeignKey("profiles.id"), nullable=False)
    requester_name = Column(Text, nullable=False)
    role = Column(Text, nullable=False)
    department = Column(Text, nullable=True)
    requested_category = Column(Text, nullable=False)
    title = Column(Text, nullable=False)
    attendance = Column(Integer, nullable=False)
    duration_periods = Column(Integer, nullable=False)
    windows = Column(JSONB, nullable=False, default=list)
    room_types = Column(JSONB, nullable=False, default=list)
    needs = Column(JSONB, nullable=False, default=list)
    requested_room = Column(Text, nullable=True)
    mandatory_for_groups = Column(JSONB, nullable=False, default=list)
    series_id = Column(Text, nullable=True)
    raw_text = Column(Text, nullable=False, default="")
    cancelled = Column(Boolean, nullable=False, default=False)
    cancelled_at = Column(DateTime(timezone=True), nullable=True)
    cancelled_by = Column(UUID(as_uuid=True), ForeignKey("profiles.id"), nullable=True)
    cancel_note = Column(Text, nullable=True)

    __table_args__ = (
        CheckConstraint("attendance > 0", name="br_attendance_positive"),
        CheckConstraint("duration_periods > 0", name="br_duration_positive"),
    )


class BookingRun(Base):
    __tablename__ = "booking_runs"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    timetable_run_id = Column(UUID(as_uuid=True), ForeignKey("timetable_runs.id"), nullable=True)
    total_requests = Column(Integer, nullable=False)
    approved_count = Column(Integer, nullable=False, default=0)
    rejected_count = Column(Integer, nullable=False, default=0)
    alt_count = Column(Integer, nullable=False, default=0)
    created_by = Column(UUID(as_uuid=True), ForeignKey("profiles.id"), nullable=False)
    created_at = Column(DateTime(timezone=True), nullable=False, default=datetime.now)

    decisions = relationship("BookingDecisionRow", back_populates="run", cascade="all, delete-orphan")


class BookingDecisionRow(Base):
    __tablename__ = "booking_decisions"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    run_id = Column(UUID(as_uuid=True), ForeignKey("booking_runs.id", ondelete="CASCADE"), nullable=False)
    request_id = Column(Text, nullable=False)
    title = Column(Text, nullable=False)
    requester = Column(Text, nullable=False)
    status = Column(Text, nullable=False)
    allocated = Column(JSONB, nullable=True)
    alternative = Column(JSONB, nullable=True)
    reasons = Column(JSONB, nullable=False, default=list)

    run = relationship("BookingRun", back_populates="decisions")

    __table_args__ = (
        CheckConstraint(
            "status IN ('approved', 'rejected', 'alternative_offered')",
            name="bd_status_check",
        ),
        UniqueConstraint("run_id", "request_id", name="uq_bd_run_request"),
    )


class ExamRun(Base):
    __tablename__ = "exam_runs"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    total_exams = Column(Integer, nullable=False)
    scheduled_count = Column(Integer, nullable=False)
    unscheduled_count = Column(Integer, nullable=False, default=0)
    slots_used = Column(Integer, nullable=False, default=0)
    slots_available = Column(Integer, nullable=False, default=0)
    is_active = Column(Boolean, nullable=False, default=False)
    created_by = Column(UUID(as_uuid=True), ForeignKey("profiles.id"), nullable=False)
    created_at = Column(DateTime(timezone=True), nullable=False, default=datetime.now)

    entries = relationship("ExamEntry", back_populates="run", cascade="all, delete-orphan")


class ExamEntry(Base):
    __tablename__ = "exam_entries"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    run_id = Column(UUID(as_uuid=True), ForeignKey("exam_runs.id", ondelete="CASCADE"), nullable=False)
    exam_id = Column(Text, nullable=False)
    course_ids = Column(JSONB, nullable=False, default=list)
    groups = Column(JSONB, nullable=False, default=list)
    size = Column(Integer, nullable=False)
    day = Column(Text, nullable=False)
    session = Column(Text, nullable=False)

    run = relationship("ExamRun", back_populates="entries")
    room_allocations = relationship("ExamRoomAllocation", back_populates="entry", cascade="all, delete-orphan")

    __table_args__ = (
        CheckConstraint("session IN ('AM', 'PM')", name="ee_session_check"),
        UniqueConstraint("run_id", "exam_id", name="uq_ee_run_exam"),
    )


class ExamRoomAllocation(Base):
    __tablename__ = "exam_room_allocations"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    entry_id = Column(UUID(as_uuid=True), ForeignKey("exam_entries.id", ondelete="CASCADE"), nullable=False)
    room_id = Column(Text, nullable=False)
    seats_used = Column(Integer, nullable=False)

    entry = relationship("ExamEntry", back_populates="room_allocations")

    __table_args__ = (
        CheckConstraint("seats_used > 0", name="era_seats_positive"),
    )


class RescheduleProposal(Base):
    __tablename__ = "reschedule_proposals"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    proposal_id = Column(Text, nullable=False, unique=True)
    timetable_run_id = Column(UUID(as_uuid=True), ForeignKey("timetable_runs.id"), nullable=True)
    status = Column(Text, nullable=False, default="feasible")
    solver_status = Column(Text, nullable=False, default="")
    total_sessions = Column(Integer, nullable=False, default=0)
    frozen_count = Column(Integer, nullable=False, default=0)
    rescheduled_count = Column(Integer, nullable=False, default=0)
    moved_count = Column(Integer, nullable=False, default=0)
    added_count = Column(Integer, nullable=False, default=0)
    unscheduled_count = Column(Integer, nullable=False, default=0)
    conflicts = Column(JSONB, nullable=False, default=list)
    solve_time_seconds = Column(Float, nullable=False, default=0)
    approved_schedule = Column(JSONB, nullable=True)
    approved = Column(Boolean, nullable=False, default=False)
    proposed_by = Column(UUID(as_uuid=True), ForeignKey("profiles.id"), nullable=False)
    approved_by = Column(UUID(as_uuid=True), ForeignKey("profiles.id"), nullable=True)
    approved_at = Column(DateTime(timezone=True), nullable=True)
    created_at = Column(DateTime(timezone=True), nullable=False, default=datetime.now)

    changes = relationship("RescheduleChange", back_populates="proposal", cascade="all, delete-orphan")

    __table_args__ = (
        CheckConstraint(
            "status IN ('feasible', 'infeasible')",
            name="rp_status_check",
        ),
        CheckConstraint(
            "approved_by IS NULL OR approved_by IS DISTINCT FROM proposed_by",
            name="no_self_approval",
        ),
    )


class RescheduleChange(Base):
    __tablename__ = "reschedule_changes"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    proposal_id = Column(UUID(as_uuid=True), ForeignKey("reschedule_proposals.id", ondelete="CASCADE"), nullable=False)
    session_id = Column(Text, nullable=False)
    kind = Column(Text, nullable=False)
    before_day = Column(Text, nullable=True)
    before_period = Column(Integer, nullable=True)
    before_room_id = Column(Text, nullable=True)
    after_day = Column(Text, nullable=True)
    after_period = Column(Integer, nullable=True)
    after_room_id = Column(Text, nullable=True)
    reason = Column(Text, nullable=False, default="")

    proposal = relationship("RescheduleProposal", back_populates="changes")

    __table_args__ = (
        CheckConstraint(
            "kind IN ('moved', 'added', 'unscheduled')",
            name="rc_kind_check",
        ),
    )


class AuditLog(Base):
    __tablename__ = "audit_log"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    actor_id = Column(UUID(as_uuid=True), ForeignKey("profiles.id"), nullable=False)
    action = Column(Text, nullable=False)
    target_type = Column(Text, nullable=False, default="")
    target_id = Column(Text, nullable=False, default="")
    detail = Column(JSONB, nullable=False, default=dict)
    ip_address = Column(INET, nullable=True)
    created_at = Column(DateTime(timezone=True), nullable=False, default=datetime.now)

